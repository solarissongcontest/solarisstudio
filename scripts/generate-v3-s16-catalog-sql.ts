import {writeFileSync} from "node:fs";
import {V3_S16_CRITICAL_DOMAINS} from "../src/lib/v3-s16-mutation-authority";
import {S16_FUNCTION_CATALOG_SQL,S16_ROLE_AND_DEFAULT_CATALOG_SQL,s16TableCatalogSql} from "../src/lib/v3-s16-catalog";
// The guarded collector is the executable entrypoint. This generated SQL is
// inspectable diagnostic source, not independently SHA-bound release evidence.
const relations = [...new Set(V3_S16_CRITICAL_DOMAINS.flatMap(d=>d.canonicalTables))].sort();
const query = s16TableCatalogSql("public.__s16_relation__").replaceAll("'public.__s16_relation__'", "critical.name").replace(/;$/, "");
const tables = `with critical(name) as (values ${relations.map(name=>"('"+name+"')").join(",")}) select jsonb_agg(entry) from (select (${query})::jsonb entry from critical) rows;`;
writeFileSync(".github/scripts/sql/v3-s16-canonical-mutation-authority.sql",[
 "\\set ON_ERROR_STOP on", "-- Generated by scripts/generate-v3-s16-catalog-sql.ts; do not hand-edit.",
 "-- Use only through an isolated local database procedure. This file does not certify S16.",
 "begin read only;", "set local search_path=pg_catalog;", S16_ROLE_AND_DEFAULT_CATALOG_SQL,
 tables,
 S16_FUNCTION_CATALOG_SQL,"rollback;", "",
].join("\n"));
