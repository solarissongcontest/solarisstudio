do $policy_consolidation$
declare
  v_target record;
  v_policy record;
  v_anon_qual text;
  v_auth_qual text;
  v_roles_sql text;
  v_insert_name text;
  v_update_name text;
  v_delete_name text;
  v_check text;
begin
  for v_target in
    select *
    from (values
      ('public','content_events'),
      ('public','contest_entities'),
      ('public','countries'),
      ('public','country_accounts'),
      ('public','country_edition_identities'),
      ('public','country_hod_edition_claims'),
      ('public','country_media'),
      ('public','country_profile_sections'),
      ('public','country_profiles'),
      ('public','country_themes'),
      ('public','editions'),
      ('public','entries'),
      ('public','jury_ballot_submissions'),
      ('public','jury_votes'),
      ('public','jury_voting_windows'),
      ('public','participants'),
      ('public','prediction_rounds'),
      ('public','results'),
      ('public','shows'),
      ('public','submission_rounds'),
      ('public','televote_votes'),
      ('public','themes'),
      ('public','user_roles'),
      ('public','voters'),
      ('televoting','combined_televote_component_results'),
      ('televoting','combined_televote_results'),
      ('televoting','countries'),
      ('televoting','editions'),
      ('televoting','round_countries'),
      ('televoting','round_entries'),
      ('televoting','round_results'),
      ('televoting','rounds'),
      ('televoting','televote_aggregation_participants'),
      ('televoting','televote_aggregations')
    ) as targets(schema_name, table_name)
  loop
    if to_regclass(format('%I.%I', v_target.schema_name, v_target.table_name)) is null then
      raise exception 'Expected RLS table is missing: %.%', v_target.schema_name, v_target.table_name;
    end if;

    -- Capture the exact current SELECT union before changing any policy.
    select string_agg('(' || p.qual || ')', ' OR ' order by p.policyname)
    into v_anon_qual
    from pg_policies p
    where p.schemaname = v_target.schema_name
      and p.tablename = v_target.table_name
      and p.cmd in ('SELECT','ALL')
      and p.qual is not null
      and ('public' = any(p.roles) or 'anon' = any(p.roles));

    select string_agg('(' || p.qual || ')', ' OR ' order by p.policyname)
    into v_auth_qual
    from pg_policies p
    where p.schemaname = v_target.schema_name
      and p.tablename = v_target.table_name
      and p.cmd in ('SELECT','ALL')
      and p.qual is not null
      and ('public' = any(p.roles) or 'authenticated' = any(p.roles));

    -- Split every browser-applicable FOR ALL policy so it no longer contributes
    -- an extra SELECT predicate.
    for v_policy in
      select *
      from pg_policies p
      where p.schemaname = v_target.schema_name
        and p.tablename = v_target.table_name
        and p.cmd = 'ALL'
        and (
          'public' = any(p.roles)
          or 'anon' = any(p.roles)
          or 'authenticated' = any(p.roles)
        )
      order by p.policyname
    loop
      select string_agg(format('%I', role_name), ', ')
      into v_roles_sql
      from unnest(v_policy.roles) as role_name;

      v_check := coalesce(v_policy.with_check, v_policy.qual, 'true');
      v_insert_name := left(v_policy.policyname || ' insert', 63);
      v_update_name := left(v_policy.policyname || ' update', 63);
      v_delete_name := left(v_policy.policyname || ' delete', 63);

      execute format('drop policy %I on %I.%I',
        v_policy.policyname, v_target.schema_name, v_target.table_name);

      execute format('drop policy if exists %I on %I.%I',
        v_insert_name, v_target.schema_name, v_target.table_name);
      execute format('drop policy if exists %I on %I.%I',
        v_update_name, v_target.schema_name, v_target.table_name);
      execute format('drop policy if exists %I on %I.%I',
        v_delete_name, v_target.schema_name, v_target.table_name);

      execute format(
        'create policy %I on %I.%I for insert to %s with check (%s)',
        v_insert_name, v_target.schema_name, v_target.table_name, v_roles_sql, v_check
      );
      execute format(
        'create policy %I on %I.%I for update to %s using (%s) with check (%s)',
        v_update_name, v_target.schema_name, v_target.table_name, v_roles_sql,
        coalesce(v_policy.qual, 'true'), v_check
      );
      execute format(
        'create policy %I on %I.%I for delete to %s using (%s)',
        v_delete_name, v_target.schema_name, v_target.table_name, v_roles_sql,
        coalesce(v_policy.qual, 'true')
      );
    end loop;

    -- Remove the old SELECT policies that applied to browser roles. Their exact
    -- unions were captured above.
    for v_policy in
      select *
      from pg_policies p
      where p.schemaname = v_target.schema_name
        and p.tablename = v_target.table_name
        and p.cmd = 'SELECT'
        and (
          'public' = any(p.roles)
          or 'anon' = any(p.roles)
          or 'authenticated' = any(p.roles)
        )
      order by p.policyname
    loop
      execute format('drop policy %I on %I.%I',
        v_policy.policyname, v_target.schema_name, v_target.table_name);
    end loop;

    execute format('drop policy if exists %I on %I.%I',
      'solaris consolidated anon read', v_target.schema_name, v_target.table_name);
    execute format('drop policy if exists %I on %I.%I',
      'solaris consolidated authenticated read', v_target.schema_name, v_target.table_name);

    if v_anon_qual is not null then
      execute format(
        'create policy %I on %I.%I for select to anon using (%s)',
        'solaris consolidated anon read',
        v_target.schema_name, v_target.table_name, v_anon_qual
      );
    end if;

    if v_auth_qual is not null then
      execute format(
        'create policy %I on %I.%I for select to authenticated using (%s)',
        'solaris consolidated authenticated read',
        v_target.schema_name, v_target.table_name, v_auth_qual
      );
    end if;
  end loop;
end
$policy_consolidation$;

do $verify$
declare
  v_target record;
  v_count integer;
begin
  if to_regclass('public.contest_entities_country_id_idx') is null
     or to_regclass('public.country_hod_edition_claims_country_id_idx') is null
     or to_regclass('public.country_hod_edition_claims_edition_id_idx') is null
     or to_regclass('public.jury_votes_receiving_country_id_idx') is null
     or to_regclass('public.jury_votes_voter_country_id_idx') is null
     or to_regclass('public.jury_votes_voter_entity_id_idx') is null
     or to_regclass('public.participants_country_id_idx') is null
     or to_regclass('public.results_country_id_idx') is null
     or to_regclass('public.televote_votes_country_id_idx') is null
     or to_regclass('public.voters_contest_entity_id_idx') is null
     or to_regclass('public.voters_country_id_idx') is null then
    raise exception 'Expected high-volume FK indexes are missing';
  end if;

  if exists (select 1 from pg_namespace where nspname = 'migration_staging') then
    raise exception 'migration_staging still exists';
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'private.studio2_notice_deletion_audit'::regclass
      and contype = 'p'
  ) then
    raise exception 'private.studio2_notice_deletion_audit still has no primary key';
  end if;

  for v_target in
    select *
    from (values
      ('public','content_events'),('public','contest_entities'),('public','countries'),
      ('public','country_accounts'),('public','country_edition_identities'),
      ('public','country_hod_edition_claims'),('public','country_media'),
      ('public','country_profile_sections'),('public','country_profiles'),
      ('public','country_themes'),('public','editions'),('public','entries'),
      ('public','jury_ballot_submissions'),('public','jury_votes'),
      ('public','jury_voting_windows'),('public','participants'),
      ('public','prediction_rounds'),('public','results'),('public','shows'),
      ('public','submission_rounds'),('public','televote_votes'),('public','themes'),
      ('public','user_roles'),('public','voters'),
      ('televoting','combined_televote_component_results'),
      ('televoting','combined_televote_results'),('televoting','countries'),
      ('televoting','editions'),('televoting','round_countries'),
      ('televoting','round_entries'),('televoting','round_results'),
      ('televoting','rounds'),('televoting','televote_aggregation_participants'),
      ('televoting','televote_aggregations')
    ) as targets(schema_name, table_name)
  loop
    select count(*) into v_count
    from pg_policies p
    where p.schemaname = v_target.schema_name
      and p.tablename = v_target.table_name
      and p.cmd in ('SELECT','ALL')
      and ('public' = any(p.roles) or 'anon' = any(p.roles));

    if v_count > 1 then
      raise exception 'Multiple anon SELECT policies remain on %.%: %',
        v_target.schema_name, v_target.table_name, v_count;
    end if;

    select count(*) into v_count
    from pg_policies p
    where p.schemaname = v_target.schema_name
      and p.tablename = v_target.table_name
      and p.cmd in ('SELECT','ALL')
      and ('public' = any(p.roles) or 'authenticated' = any(p.roles));

    if v_count > 1 then
      raise exception 'Multiple authenticated SELECT policies remain on %.%: %',
        v_target.schema_name, v_target.table_name, v_count;
    end if;
  end loop;
end
$verify$;

