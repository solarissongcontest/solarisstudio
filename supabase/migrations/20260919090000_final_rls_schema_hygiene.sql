-- Final RLS + schema hygiene.
--
-- 1. Remove production-only, empty migration staging tables.
-- 2. Give the private notice-deletion audit log a durable primary key.
-- 3. Preserve the exact union of current anon/authenticated SELECT access while
--    consolidating it to one policy per role and splitting authenticated FOR ALL
--    write policies into INSERT / UPDATE / DELETE policies.
--
-- This removes policy-evaluation duplication without changing application
-- authorization semantics.

do $staging_cleanup$
declare
  v_table record;
  v_rows bigint;
begin
  if exists (select 1 from pg_namespace where nspname = 'migration_staging') then
    if exists (
      select 1
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'migration_staging'
    ) then
      raise exception 'migration_staging contains functions and cannot be removed automatically';
    end if;

    for v_table in
      select c.oid, c.relname
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'migration_staging'
        and c.relkind = 'r'
      order by c.relname
    loop
      execute format('select count(*) from migration_staging.%I', v_table.relname)
        into v_rows;
      if v_rows <> 0 then
        raise exception 'migration_staging.% is not empty (% rows)', v_table.relname, v_rows;
      end if;

      if exists (
        select 1
        from pg_constraint con
        where con.contype = 'f'
          and con.confrelid = v_table.oid
          and con.conrelid <> v_table.oid
      ) then
        raise exception 'migration_staging.% is referenced by a foreign key', v_table.relname;
      end if;
    end loop;

    execute 'drop schema migration_staging cascade';
  end if;
end
$staging_cleanup$;

alter table private.studio2_notice_deletion_audit
